import type { FurnitureUse } from './shop';

export type FurnitureCategory =
  'bedroom' | 'bathroom' | 'kitchen' | 'living' | 'dining' | 'office' | 'decor';

export interface FurnitureDef {
  id: string;
  name: string;
  category: FurnitureCategory;
  /** Model file inside the `interiors` pack. */
  file: string;
  /** Floor cells it covers when not turned (1 cell = 1 metre). */
  w: number;
  d: number;
  price: number;
  /** Adds to the home's comfort, which lifts mood. */
  comfort: number;
  use?: FurnitureUse;
  /** How well it does its `use`; a better bed restores energy faster. */
  rate?: number;
  /** Lies on the floor: other furniture may stand on it, but not another flat item. */
  flat?: boolean;
}

